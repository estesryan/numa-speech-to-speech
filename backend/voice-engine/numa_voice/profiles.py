"""Profiles: Numa's model selections, rendered into upstream speech-to-speech YAML with project-local paths.

A profile is upstream's own configuration format (see upstream docs/configuration.md) plus one Numa convention:
any string value of the form `numa-model:<manifest id>` or `numa-model:<manifest id>#<file>` is replaced by the
absolute path of that model (or file) under the models root. Profiles overlay `profiles/base.yaml`; the LLM prompt
comes from the selected persona (`personas.py`), never from a profile. The merged result is validated with
upstream's own config resolver before anything starts.
"""

from __future__ import annotations

import copy
from pathlib import Path
from typing import Any

import yaml

from .manifest import Model, load_manifest
from .paths import GENERATED_DIR, PROFILES_DIR, models_root
from .personas import DEFAULT_PERSONA, load_persona

PLACEHOLDER = "numa-model:"
DEFAULT_PROFILE = "fast"


class ProfileError(ValueError):
    pass


def available_profiles() -> list[str]:
    return sorted(p.stem for p in PROFILES_DIR.glob("*.yaml") if p.stem != "base")


def _merge(base: Any, overlay: Any) -> Any:
    if isinstance(base, dict) and isinstance(overlay, dict):
        out = dict(base)
        for k, v in overlay.items():
            out[k] = _merge(base[k], v) if k in base else copy.deepcopy(v)
        return out
    return copy.deepcopy(overlay)


def load_profile(name: str) -> dict[str, Any]:
    path = PROFILES_DIR / f"{name}.yaml"
    if name == "base" or not path.exists():
        raise ProfileError(f"unknown profile {name!r}; available: {', '.join(available_profiles())}")
    base = yaml.safe_load((PROFILES_DIR / "base.yaml").read_text())
    profile = _merge(base, yaml.safe_load(path.read_text()))
    if "init_chat_prompt" in profile.get("blocks", {}).get("llm", {}).get("settings", {}):
        raise ProfileError(f"profile {name!r} sets init_chat_prompt; the prompt comes from personas/ (--persona)")
    return profile


def _references(node: Any) -> list[str]:
    if isinstance(node, dict):
        return [r for v in node.values() for r in _references(v)]
    if isinstance(node, list):
        return [r for v in node for r in _references(v)]
    if isinstance(node, str) and node.startswith(PLACEHOLDER):
        return [node[len(PLACEHOLDER):].split("#", 1)[0]]
    return []


def required_models(profile: dict[str, Any]) -> list[str]:
    """Manifest ids a profile needs: everything it references by placeholder, plus `numa.requires`."""
    ids = list(dict.fromkeys(profile.get("numa", {}).get("requires", []) + _references(profile)))
    manifest = load_manifest()
    unknown = [i for i in ids if i not in manifest]
    if unknown:
        raise ProfileError(f"profile references models missing from the manifest: {unknown}")
    return ids


def _resolve(node: Any, manifest: dict[str, Model], root: Path) -> Any:
    if isinstance(node, dict):
        return {k: _resolve(v, manifest, root) for k, v in node.items()}
    if isinstance(node, list):
        return [_resolve(v, manifest, root) for v in node]
    if isinstance(node, str) and node.startswith(PLACEHOLDER):
        mid, _, file = node[len(PLACEHOLDER):].partition("#")
        path = manifest[mid].directory(root) / file if file else manifest[mid].directory(root)
        if not path.exists():
            raise ProfileError(f"{mid}: {path} is missing; run `numa-voice models download --profile ...`")
        return str(path)
    return node


def resolve_profile(name: str, *, persona: str = DEFAULT_PERSONA, speakers: bool = False,
                    root: Path | None = None) -> dict[str, Any]:
    """The upstream configuration document for a profile and persona, with absolute model paths. Nothing is written."""
    root = root or models_root()
    profile = load_profile(name)
    required_models(profile)
    doc = _resolve({k: v for k, v in profile.items() if k != "numa"}, load_manifest(), root)
    doc["blocks"]["llm"]["settings"]["init_chat_prompt"] = load_persona(persona).system_prompt()
    if speakers:
        doc.setdefault("runtime", {}).setdefault("client", {})["block_mic_during_playback"] = True
    return doc


def realtime_policy(name: str) -> dict[str, Any]:
    """The profile's `numa.realtime` settings (WebSocket Origin policy)."""
    return load_profile(name).get("numa", {}).get("realtime", {})


def write_resolved(name: str, *, persona: str = DEFAULT_PERSONA, speakers: bool = False,
                   root: Path | None = None) -> Path:
    """Render, validate with upstream's resolver, and write `.generated/<profile>-<persona>[-speakers].yaml`."""
    doc = resolve_profile(name, persona=persona, speakers=speakers, root=root)
    GENERATED_DIR.mkdir(exist_ok=True)
    out = GENERATED_DIR / f"{name}-{persona}{'-speakers' if speakers else ''}.yaml"
    out.write_text("# Generated by numa-voice from profiles/ and personas/; do not edit.\n" + yaml.safe_dump(doc, sort_keys=False))
    from speech_to_speech.config import load_config, resolve_config

    resolve_config(load_config(out), include_client=True)  # raises on any upstream schema error
    return out
